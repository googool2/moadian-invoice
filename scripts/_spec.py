def status(field: str, inty: int, inp: int) -> str | None:
    """Return M/O/C/- for a field in a type/pattern, or None if not in Table 1."""
    row = MATRIX.get(field)
    if row is None or (inty, inp) not in MATRIX_COLUMNS:
        return None
    return row.replace("/", "")[MATRIX_COLUMNS.index((inty, inp))]
